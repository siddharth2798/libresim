#!/usr/bin/env python3
"""Writes .cache/code_map.md: one line per Godot script or shader under game/.

    path | class_name | extends | purpose (first doc-comment sentence)

graphify cannot read GDScript, so this is the cheap "where is X" lookup for game code: grep it instead of
exploring (grep -i "route" .cache/code_map.md). Standard library only, well under a second.

    tools/code_map.py                 write .cache/code_map.md (only when the content changed)
    tools/code_map.py --stdout        print instead of writing
    tools/code_map.py --check         print how many files have no purpose line
    tools/code_map.py --install-hook  refresh it after commit, merge, checkout and rewrite (next to graphify's hook)
    tools/code_map.py --uninstall-hook
    tools/code_map.py --self-test
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCAN = ROOT / "game"
OUT = ROOT / ".cache" / "code_map.md"
EXTS = {".gd", ".gdshader", ".gdshaderinc"}
SKIP_DIRS = {".godot", "__pycache__", "addons"}
HEAD_LINES = 60  # a header comment sits near the top
MAX_PURPOSE = 110
HOOKS = ["post-commit", "post-merge", "post-checkout", "post-rewrite"]
BLOCK_START = "# libresim-code-map-start"
BLOCK_END = "# libresim-code-map-end"
BLOCK = BLOCK_START + """
# Refreshes .cache/code_map.md (standard library only, well under a second). Installed by: tools/code_map.py --install-hook
(
  cd "$(git rev-parse --show-toplevel 2>/dev/null)" 2>/dev/null || exit 0
  PY=tools/.venv/bin/python; [ -x "$PY" ] || PY=python3
  [ -f tools/code_map.py ] && "$PY" tools/code_map.py >/dev/null 2>&1
) || true
""" + BLOCK_END + "\n"

CLASS_RE = re.compile(r"^class_name\s+(\w+)")
EXTENDS_RE = re.compile(r"^extends\s+(\S+)")
SHADER_TYPE_RE = re.compile(r"^shader_type\s+(\w+)")


def sentence(text: str) -> str:
    """The first sentence of a comment, one line, at most MAX_PURPOSE characters, no table separators."""
    text = " ".join(text.replace("|", "/").split())
    m = re.search(r"\.(\s|$)", text)
    if m and m.start() < MAX_PURPOSE:
        text = text[: m.start()]
    if len(text) > MAX_PURPOSE:
        text = text[: MAX_PURPOSE - 1].rstrip() + "…"
    return text


def meaningful(comment: str) -> str:
    """Comment text without the marker characters; empty for a rule line such as ## ----- or //====."""
    text = comment.strip().lstrip("#/*! ").rstrip("*/ ").strip()
    return text if re.search(r"[A-Za-z0-9]", text) else ""


def describe(name: str, lines: list) -> tuple:
    """(class_name, extends, purpose) from the top of one file."""
    shader = name.endswith((".gdshader", ".gdshaderinc"))
    cls = ""
    ext = "include" if name.endswith(".gdshaderinc") else ""
    doc = ""
    plain = ""
    in_block = False
    for raw in lines[:HEAD_LINES]:
        line = raw.strip()
        if shader:
            m = SHADER_TYPE_RE.match(line)
            if m:
                ext = "shader:" + m.group(1)
            if line.startswith("/*") or in_block:
                in_block = not line.rstrip().endswith("*/")
                text = meaningful(line)
                if text and not doc:
                    doc = text
            elif line.startswith("//"):
                text = meaningful(line)
                if text and not doc:
                    doc = text
            continue
        m = CLASS_RE.match(line)
        if m and not cls:
            cls = m.group(1)
        m = EXTENDS_RE.match(line)
        if m and not ext:
            ext = m.group(1).strip('"')
        if line.startswith("##"):
            text = meaningful(line)
            if text and not doc:
                doc = text
        elif line.startswith("#") and not line.startswith("#!"):
            text = meaningful(line)
            if text and not plain:
                plain = text
    return cls, ext, sentence(doc or plain)


def collect() -> list:
    rows = []
    for path in sorted(SCAN.rglob("*")):
        if path.suffix not in EXTS or any(p in SKIP_DIRS for p in path.relative_to(SCAN).parts):
            continue
        try:
            with open(path, encoding="utf-8", errors="replace") as f:
                lines = [next(f, "") for _ in range(HEAD_LINES)]
        except OSError:
            continue
        cls, ext, purpose = describe(path.name, lines)
        rows.append((path.relative_to(ROOT).as_posix(), cls or "-", ext or "-", purpose or "-"))
    return rows


def render(rows: list) -> str:
    blank = sum(1 for r in rows if r[3] == "-")
    head = [
        "# libresim code map (generated by tools/code_map.py, do not edit)",
        "# Godot scripts and shaders under game/: path | class_name | extends | purpose (first doc-comment sentence).",
        f"# {len(rows)} files, {blank} without a purpose line. Find things with: grep -i \"<name or word>\" .cache/code_map.md",
    ]
    return "\n".join(head + [" | ".join(r) for r in rows]) + "\n"


def write(text: str) -> bool:
    """Writes only when the content changed, so a commit hook never churns the file."""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if OUT.exists() and OUT.read_text(encoding="utf-8") == text:
        return False
    OUT.write_text(text, encoding="utf-8")
    return True


def hooks_dir() -> Path:
    out = subprocess.run(["git", "rev-parse", "--git-path", "hooks"], cwd=ROOT, capture_output=True, text=True, check=True)
    p = Path(out.stdout.strip())
    return p if p.is_absolute() else ROOT / p


def strip_block(text: str) -> str:
    a = text.find(BLOCK_START)
    b = text.find(BLOCK_END)
    if a < 0 or b < a:
        return text
    return (text[:a].rstrip("\n") + "\n" + text[b + len(BLOCK_END):].lstrip("\n")).lstrip("\n") if text[:a].strip() else text[b + len(BLOCK_END):].lstrip("\n")


def install_hook(remove: bool = False) -> None:
    d = hooks_dir()
    d.mkdir(parents=True, exist_ok=True)
    for name in HOOKS:
        f = d / name
        text = f.read_text(encoding="utf-8") if f.exists() else "#!/bin/sh\n"
        text = strip_block(text)
        if not remove:
            text = text.rstrip("\n") + "\n\n" + BLOCK
        f.write_text(text, encoding="utf-8")
        f.chmod(0o755)
        print(f"{name}: {'removed' if remove else 'installed'} ({f})")


def self_test() -> None:
    cls, ext, purpose = describe("a.gd", ["class_name Foo", "extends Node", "## Does the thing. More detail here.", "var x"])
    assert (cls, ext, purpose) == ("Foo", "Node", "Does the thing"), (cls, ext, purpose)
    assert describe("b.gd", ["extends RefCounted", "#!/x", "# plain note", "func f(): pass"])[2] == "plain note"
    assert describe("c.gd", ["extends Node", "## ------", "## Real line"])[2] == "Real line"
    assert describe("d.gdshader", ["shader_type spatial;", "// Draws | the sky. Second sentence."])[1:] == ("shader:spatial", "Draws / the sky")
    assert describe("e.gdshaderinc", ["/* Shared ramp", " * more */", "float f(){return 1.0;}"])[1:] == ("include", "Shared ramp")
    assert len(sentence("x" * 300)) == MAX_PURPOSE
    block = "#!/bin/sh\necho a\n\n" + BLOCK
    assert strip_block(block).strip() == "#!/bin/sh\necho a"
    assert strip_block("#!/bin/sh\necho a\n") == "#!/bin/sh\necho a\n"
    print("self-test ok")


def main(argv: list) -> int:
    if "--self-test" in argv:
        self_test()
    elif "--install-hook" in argv:
        install_hook()
    elif "--uninstall-hook" in argv:
        install_hook(remove=True)
    elif "--stdout" in argv:
        sys.stdout.write(render(collect()))
    elif "--check" in argv:
        rows = collect()
        for r in rows:
            if r[3] == "-":
                print(r[0])
        print(f"{len(rows)} files, {sum(1 for r in rows if r[3] == '-')} without a purpose line")
    else:
        text = render(collect())
        print(("wrote " if write(text) else "unchanged ") + str(OUT.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
