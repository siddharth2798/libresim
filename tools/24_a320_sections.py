"""Assemble game/aircraft/a320/model_sections.json (DRAFT, not loaded by the game: aircraft.json does not exist yet)
from the converter outputs (models/exterior_pivots.json, models/interior_info.json) plus the hand-set numbers below.
Ready to paste into the future aircraft.json: `model`, `cockpit`, `lights`, `registration`, `cameras`.
Usage: tools/.venv/bin/python -I tools/24_a320_sections.py   (after the two Blender conversions)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
M = ROOT / "game/aircraft/a320/models"
CG = (-2.4335, 0.0, -0.934)  # config.json mass.empty_cg_m (cameras are relative to the CG)


def lamp(switch, pos, energy, rng, angle, beam, tilt):
    return {"switch": switch, "pos": pos, "energy": energy, "range": rng, "angle": angle, "beam": beam, "tilt": tilt}


def main():
    piv = json.loads((M / "exterior_pivots.json").read_text())
    info = json.loads((M / "interior_info.json").read_text())
    surfaces = {}
    for k, v in piv.items():
        if v["drive"] == "n1_spin":
            continue
        e = {"drive": v["drive"], "sign": v["sign"]}
        if "map" in v:
            e["map"] = v["map"]
        surfaces[k] = e
    props = [{"pivot": "fan_L", "engine": 0, "sign": 1.0, "visual_rate": 0.012},
             {"pivot": "fan_R", "engine": 1, "sign": 1.0, "visual_rate": 0.012}]
    spots = {}
    names = {"pfd": "pfd_cpt", "nd": "nd_cpt", "ewd": "ewd", "sd": "sd", "mcdu": "mcdu_cpt", "iesi": "iesi",
             "pfd_fo": "pfd_fo", "nd_fo": "nd_fo", "mcdu_fo": "mcdu_fo"}
    for k, sname in names.items():
        s = info["screens"][sname]
        spots[k] = {"pos": s["centre"], "size": s["width"], "round": False}
    out = {
        "_note": "DRAFT for the future game/aircraft/a320/aircraft.json (P9); generated by tools/24_a320_sections.py, not loaded by the game. Frame: glb origin = structural origin (model.origin_m 0).",
        "_needs": [
            "aircraft_model.gd drives: slat_deg, stabilizer_deg (deg), spoiler_<l|r><1-5>_deg, gear_pos (0 up..1 down) with the piecewise 'map' [[value, degrees]] key, nose_steer_deg, wheel_*_rad (spin), reverser (0..1): extend _animate_glb; today only elevator, aileron, rudder, flap_deg exist.",
            "registration: the right fuselage side's texture island is upside down in the atlas: a second target needs a 'rotate': 180 key in registration_paint.gd (left side only below).",
            "lights/cameras numbers are first guesses (checked only by screenshots).",
        ],
        "model": {"origin_m": [0.0, 0.0, 0.0], "surfaces": surfaces, "propellers": props},
        "cockpit": {"eye": info["eye"], "panel_mesh": info["panel_mesh"], "spots": spots, "screens": info["screens"]},
        "lights": {
            "nav": [
                {"pos": [1.9, -17.13, 0.5], "side": "left", "color": "red", "size": 1.4, "range": 4.0, "omni_off": [0.4, 0.15, 0]},
                {"pos": [1.9, 17.13, 0.5], "side": "right", "color": "green", "size": 1.4, "range": 4.0, "omni_off": [-0.4, 0.15, 0]},
                {"pos": [18.6, 0.0, 0.8], "side": "tail", "color": "white", "size": 1.2, "range": 3.0, "omni_off": [0, 0.2, 0.2]},
            ],
            "beacon": [
                {"pos": [-2.0, 0.0, 2.05], "color": "red", "size": 1.6, "range": 4.0, "omni_off": [0, 0.3, 0]},
                {"pos": [2.0, 0.0, -2.05], "color": "red", "size": 1.6, "range": 4.0, "omni_off": [0, -0.3, 0]},
            ],
            "strobe": [
                {"pos": [2.4, -17.13, 0.5], "color": "strobe", "size": 1.6, "range": 9.0, "omni_off": [0.8, 0.5, 0]},
                {"pos": [2.4, 17.13, 0.5], "color": "strobe", "size": 1.6, "range": 9.0, "omni_off": [-0.8, 0.5, 0]},
                {"pos": [18.7, 0.0, 1.0], "color": "strobe", "size": 1.4, "range": 7.0, "omni_off": [0, 0.5, 0.4]},
            ],
            "lamps": [
                lamp("landing", [-2.0, -2.3, -1.55], 40, 1400, 9, 24, 6),
                lamp("landing", [-2.0, 2.3, -1.55], 40, 1400, 9, 24, 6),
                lamp("taxi", [-14.0, 0.0, -2.5], 14, 450, 24, 14, 10),
            ],
        },
        "registration": {
            "source": "callsign",
            "texture": "models/exterior_fuselage.png",
            "targets": [{"erase": [2640, 440, 220, 80], "text": [2655, 450, 190, 56], "align": "center", "color": [0.16, 0.19, 0.24], "italic": False}],
            "pending_rotate_180": {"erase": [2640, 1250, 220, 80], "text": [2655, 1260, 190, 56]},
        },
        "cameras": {"chase": [55.0, 12.0], "wing": [-13.0, 2.6, 3.4], "tail": [0.0, 5.0, 31.0], "orbit_m": 60.0},
    }
    (ROOT / "game/aircraft/a320/model_sections.json").write_text(json.dumps(out, indent=1))
    print("wrote model_sections.json:", len(surfaces), "surfaces,", len(spots), "display spots")


main()
